function translit(s){
  var m={'а':'a','б':'b','в':'v','г':'g','д':'d','е':'e','ё':'e','ж':'zh','з':'z','и':'i','й':'y','к':'k','л':'l','м':'m','н':'n','о':'o','п':'p','р':'r','с':'s','т':'t','у':'u','ф':'f','х':'h','ц':'c','ч':'ch','ш':'sh','щ':'sch','ъ':'','ы':'y','ь':'','э':'e','ю':'yu','я':'ya'};
  return String(s).toLowerCase().replace(/[а-яё]/g,function(c){return m[c]!==undefined?m[c]:c;}).replace(/[^a-z0-9]+/g,'-').replace(/^-+|-+$/g,'').slice(0,55);
}

/* Полный список услуг с уникальными slug'ами и группой. У каждой — своя страница. */
const SERVICES_ALL = [];
(function(){
  var seen={};
  GROUPS.forEach(function(g){
    g.items.forEach(function(name){
      var base = CUSTOM[name] || translit(name);
      var slug = base, n = 2;
      while(seen[slug]){ slug = base + '-' + n; n++; }
      seen[slug]=1;
      SERVICES_ALL.push({ name:name, slug:slug, groupSlug:g.slug, groupName:g.name, ic:g.ic, from:g.from, custom: !!CUSTOM[name] });
    });
  });
})();

function svcHref(name, groupSlug){
  var s = SERVICES_ALL.find(function(x){ return x.name===name && (!groupSlug || x.groupSlug===groupSlug); }) || SERVICES_ALL.find(function(x){ return x.name===name; });
  return s ? s.slug+'.html' : (groupSlug ? groupSlug+'.html' : 'ekspertizy.html');
}

